// Builds the handwritten "Hi, <team>" lettering used by the /hi/<company> intro.
// Reads the companies list from portfolio-src/index.html and writes the glyph paths
// back into the HI-SCRIPTS block of the same file. Re-run it after adding a company:
//   cd /tmp && npm i --no-save opentype.js @fontsource/allura
//   NODE_PATH=/tmp/node_modules node scripts/hi-script.js
const fs = require('fs');
const path = require('path');
const opentype = require('opentype.js');

const file = path.join(__dirname, '..', 'portfolio-src', 'index.html');
let html = fs.readFileSync(file, 'utf8');

const fontPath = require.resolve('@fontsource/allura/files/allura-latin-400-normal.woff');
const buf = fs.readFileSync(fontPath);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const SIZE = 100;
const scale = SIZE / font.unitsPerEm;

// Manual layout: opentype's own text shaping throws on some script fonts.
function build(text) {
  let x = 0, prev = null;
  const glyphs = [];
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  for (const ch of text) {
    const g = font.charToGlyph(ch);
    if (prev) x += font.getKerningValue(prev, g) * scale;
    const p = g.getPath(x, 0, SIZE);
    if (p.commands.length) {
      const b = p.getBoundingBox();
      minX = Math.min(minX, b.x1); minY = Math.min(minY, b.y1);
      maxX = Math.max(maxX, b.x2); maxY = Math.max(maxY, b.y2);
      glyphs.push({ d: p.toPathData(1), x: +x.toFixed(1), a: +(g.advanceWidth * scale).toFixed(1) });
    }
    x += g.advanceWidth * scale;
    prev = g;
  }
  const pad = 8; // room for the heavier stroke
  return {
    vb: [minX - pad, minY - pad, maxX - minX + pad * 2, maxY - minY + pad * 2].map(n => +n.toFixed(1)),
    g: glyphs
  };
}

const re = /(\w+): \{name:'([^']+)'/g;
const out = {};
let m;
const block = html.slice(html.indexOf('const companies = {'), html.indexOf('const order ='));
while ((m = re.exec(block))) out[m[1]] = build(`Hi, ${m[2]} team`);

const start = '/* HI-SCRIPTS:START (generated by scripts/hi-script.js) */';
const end = '/* HI-SCRIPTS:END */';
const a = html.indexOf(start), b = html.indexOf(end);
const body = `${start}\n    const hiScripts = ${JSON.stringify(out)};\n    ${end}`;
if (a === -1) throw new Error('HI-SCRIPTS block not found in index.html');
html = html.slice(0, a) + body + html.slice(b + end.length);
fs.writeFileSync(file, html);
console.log('wrote', Object.keys(out).join(', '));
